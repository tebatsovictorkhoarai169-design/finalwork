import 'dotenv/config';
import express from 'express';
import mongoose from 'mongoose';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import authRoutes from './routes/auth.js';
import contentRoutes from './routes/contents.js';
import commentRoutes from './routes/comments.js';
import dashboardRoutes from './routes/dashboard.js';
const app = express();
app.use(helmet());
app.use(cors({ origin: process.env.CLIENT_URL?.split(',') || 'http://localhost:5173' }));
app.use(express.json({ limit: '1mb' }));
app.use(morgan('dev'));
app.use('/api', rateLimit({ windowMs: 15 * 60 * 1000, limit: 300, standardHeaders: 'draft-7', legacyHeaders: false }));
app.get('/api/health', (req, res) => res.json({ status: 'ok', service: 'OFFSET API' }));
app.use('/api/auth', authRoutes);
app.use('/api/contents', contentRoutes);
app.use('/api/comments', commentRoutes);
app.use('/api/dashboard', dashboardRoutes);
app.use((req, res) => res.status(404).json({ message: 'The requested route does not exist.' }));
app.use((error, req, res, next) => { console.error(error); res.status(error.name === 'ValidationError' ? 400 : 500).json({ message: error.name === 'ValidationError' ? error.message : 'Something went wrong. Please try again.' }); });
const port = process.env.PORT || 5000;
if (!process.env.MONGODB_URI || !process.env.JWT_SECRET) console.error('Warning: MONGODB_URI and JWT_SECRET must be configured.');
else mongoose.connect(process.env.MONGODB_URI).then(() => { console.log('MongoDB connected'); app.listen(port, () => console.log(`OFFSET API running on ${port}`)); }).catch(error => { console.error('MongoDB connection failed:', error.message); process.exit(1); });
